"""Generate flash-resident gzip pages using PlatformIO's Python installation."""
import gzip
import hashlib
from pathlib import Path


PAGES = (
    ("ROOT_PAGE", "index.html"),
    ("ADMIN_PAGE", "admin.html"),
    ("OTA_PAGE", "update.html"),
    ("CONFIG_PAGE", "config.html"),
    ("RESET_PAGE", "reset.html"),
    ("REBOOT_PAGE", "reboot.html"),
    ("RF_SNIFF_PAGE", "rf-sniff.html"),
    ("BLE_SNIFF_PAGE", "ble-sniff.html"),
)

SCRIPTS = ("html.js", "state.js", "presets.js", "api.js", "forms.js", "app.js", "fermenters.js", "sensors.js",
           "profiles.js", "plugs.js", "reporting.js", "system.js", "logs.js", "bootstrap.js")


def shared_assets(root):
    css = page_bytes(root / "web/styles/admin.css")
    js = b"\n;\n".join(page_bytes(root / "web/js" / name) for name in SCRIPTS)
    result = []
    for symbol, prefix, data in (("WEB_CSS", "c", css), ("WEB_JS", "j", js)):
        compressed = gzip.compress(data, compresslevel=9, mtime=0)
        # Keep URLs stable when another compressor encodes the same asset text.
        path = "/" + prefix + hashlib.sha256(data).hexdigest()[:8]
        result.append((symbol, path, data, compressed))
    return result


def prepared_page(root, filename, assets):
    data = page_bytes(root / "web/pages" / filename)
    if filename == "admin.html":
        for symbol, path, _, _ in assets:
            data = data.replace(("{{" + ("CSS_PATH" if symbol == "WEB_CSS" else "JS_PATH") + "}}").encode(), path.encode())
    return data


def page_bytes(path):
    # Match C++ raw-string line endings without changing meaningful whitespace.
    return path.read_text(encoding="utf-8").encode("utf-8")


def build(root):
    root = Path(root)
    lines = ["// Generated by web/build.py. Edit web/pages instead.",
             "#pragma once", "#include <Arduino.h>", ""]
    raw_total = gzip_total = 0
    assets = shared_assets(root)
    for symbol, path, _, _ in assets:
        lines.append('#define %s_PATH "%s"' % (symbol, path))
    entries = [(symbol, filename, prepared_page(root, filename, assets)) for symbol, filename in PAGES]
    entries += [(symbol, path, raw) for symbol, path, raw, _ in assets]
    for symbol, filename, raw in entries:
        compressed = gzip.compress(raw, compresslevel=9, mtime=0)
        lines.append("static const uint8_t %s[] PROGMEM = {" % symbol)
        for offset in range(0, len(compressed), 16):
            lines.append("  " + ", ".join("0x%02x" % b for b in compressed[offset:offset + 16]) + ",")
        lines.extend(["};", ""])
        print("WebUI %-14s %6d raw -> %6d gzip bytes" % (filename, len(raw), len(compressed)))
        raw_total += len(raw)
        gzip_total += len(compressed)
    output = ("\r\n".join(lines) + "\r\n").encode("ascii")
    target = root / "OurBrewbot/WebUIAssets.h"
    # Leave an identical header alone so ordinary builds remain incremental.
    if not target.exists() or target.read_bytes() != output:
        target.write_bytes(output)
    print("WebUI total          %6d raw -> %6d gzip bytes" % (raw_total, gzip_total))


if "Import" in globals():
    Import("env")
    build(env["PROJECT_DIR"])
elif __name__ == "__main__":
    build(Path(__file__).resolve().parents[1])
